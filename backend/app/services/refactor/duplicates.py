"""Deterministic duplicate-code detection (analysis only; nothing here ever edits a file).

Three evidence levels, strongest first:
* ``exact``      – identical token streams (comments and whitespace ignored).
* ``renamed``    – identical once identifiers, numbers and strings are normalised (copy with renamed variables / changed literals).
* ``structural`` – Jaccard similarity of 4-token shingles of the normalised stream at or above the threshold (copy that was then edited).
Similarity measures textual/structural overlap. It is **not** proof of equivalent behaviour. Units are functions / methods (Python via ``ast``
and ``tokenize``, JS/TS via tree-sitter) plus, for Python, windows of consecutive statements (``statement_sequence``, exact/renamed only).
"""
from __future__ import annotations

import ast
import hashlib
import io
import keyword
import textwrap
import tokenize
from collections import defaultdict
from dataclasses import dataclass, field
from typing import Any

from app.services.analysis.redaction import scrub
from app.services.refactor.common import Workspace, parser_for

PY = {"python"}
JS = {"javascript", "jsx", "typescript", "tsx"}
SHINGLE = 4
COMMON_SHINGLE_CAP = 60
KIND_RANK = {"exact": 0, "renamed": 1, "structural": 2}
GENERATED_MARKERS = ("@generated", "do not edit", "code generated", "auto-generated", "autogenerated")
GENERATED_NAMES = ("_pb2.py", "_pb2_grpc.py", ".min.js", ".bundle.js", ".generated.ts", ".d.ts")
TEST_HINTS = ("test_", "_test.", ".test.", ".spec.", "/tests/", "/test/", "/__tests__/")
OPERATORS_NOISE = {",", ";", ":", "(", ")", "[", "]", "{", "}", "NEWLINE", "INDENT", "DEDENT"}


@dataclass
class Unit:
    rel: str
    name: str
    kind: str          # function | method | statements
    start: int
    end: int
    raw: list[str]
    norm: list[str]
    lines: list[str]
    language: str

    @property
    def tokens(self) -> int:
        return len(self.raw)


@dataclass
class DupOptions:
    languages: set[str] = field(default_factory=lambda: PY | JS)
    min_lines: int = 6
    min_tokens: int = 40
    threshold: float = 0.85
    path_prefix: str = ""
    exclude_paths: list[str] = field(default_factory=list)
    exclude_tests: bool = False
    kinds: set[str] = field(default_factory=lambda: {"exact", "renamed", "structural"})
    include_statement_sequences: bool = True
    max_groups: int = 100


def _py_tokens(lines: list[str]) -> tuple[list[str], list[str]] | None:
    src = textwrap.dedent("\n".join(lines)) + "\n"
    raw: list[str] = []
    norm: list[str] = []
    try:
        for tok in tokenize.generate_tokens(io.StringIO(src).readline):
            t, s = tok.type, tok.string
            if t in (tokenize.COMMENT, tokenize.NL, tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.ENDMARKER, tokenize.ENCODING):
                continue
            raw.append(s)
            if t == tokenize.NAME:
                norm.append(s if keyword.iskeyword(s) else "ID")
            elif t == tokenize.NUMBER:
                norm.append("NUM")
            elif t == tokenize.STRING or t in (getattr(tokenize, "FSTRING_START", -1), getattr(tokenize, "FSTRING_MIDDLE", -1)):
                norm.append("STR")
            else:
                norm.append(s)
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return None
    return raw, norm


def _py_units(rel: str, text: str, o: DupOptions) -> list[Unit]:
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return []
    lines = text.split("\n")
    out: list[Unit] = []

    def add(name: str, kind: str, a: int, b: int) -> None:
        if b - a + 1 < o.min_lines:
            return
        seg = lines[a - 1:b]
        tk = _py_tokens(seg)
        if tk is None or len(tk[0]) < o.min_tokens:
            return
        out.append(Unit(rel, name, kind, a, b, tk[0], tk[1], seg, "python"))

    def visit(body: list[ast.stmt], prefix: str, in_class: bool) -> None:
        for n in body:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
                q = f"{prefix}{n.name}"
                add(q, "method" if in_class else "function", n.lineno, n.end_lineno or n.lineno)
                visit(n.body, q + ".", False)
            elif isinstance(n, ast.ClassDef):
                visit(n.body, f"{prefix}{n.name}.", True)
            elif o.include_statement_sequences and hasattr(n, "body"):
                pass
        if o.include_statement_sequences:
            stmts = [s for s in body if not isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))]
            for i in range(0, max(0, len(stmts) - 2)):
                win = stmts[i:i + 3]
                a, b = win[0].lineno, win[-1].end_lineno or win[-1].lineno
                if b - a + 1 >= o.min_lines and prefix:
                    add(f"{prefix}<statements@{a}>", "statements", a, b)

    visit(tree.body, "", False)
    return out


def _js_leaf_class(n: Any) -> str | None:
    t = n.type
    if t in ("identifier", "property_identifier", "type_identifier", "shorthand_property_identifier", "private_property_identifier"):
        return "ID"
    if t == "number":
        return "NUM"
    if t in ("string_fragment", "regex_pattern", "template_chars"):
        return "STR"
    return None


def _js_units(rel: str, text: str, language: str, o: DupOptions) -> list[Unit]:
    parser = parser_for(language)
    if parser is None:
        return []
    tree = parser.parse(text.encode("utf-8"))  # type: ignore[attr-defined]
    lines = text.split("\n")
    out: list[Unit] = []

    def leaves(node: Any, raw: list[str], norm: list[str]) -> None:
        stack = [node]
        while stack:
            cur = stack.pop()
            if cur.type == "comment":
                continue
            if cur.children:
                stack.extend(reversed(cur.children))
                continue
            s = cur.text.decode("utf-8", errors="replace")
            if not s.strip():
                continue
            raw.append(s)
            norm.append(_js_leaf_class(cur) or s)

    def add(name: str, kind: str, node: Any) -> None:
        a, b = node.start_point[0] + 1, node.end_point[0] + 1
        if b - a + 1 < o.min_lines:
            return
        raw: list[str] = []
        norm: list[str] = []
        leaves(node, raw, norm)
        if len(raw) < o.min_tokens:
            return
        out.append(Unit(rel, name, kind, a, b, raw, norm, lines[a - 1:b], language))

    stack = [(tree.root_node, "", False)]
    while stack:
        n, prefix, in_class = stack.pop()
        t = n.type
        nm = n.child_by_field_name("name") if hasattr(n, "child_by_field_name") else None
        name = nm.text.decode("utf-8", errors="replace") if nm is not None else ""
        if t in ("function_declaration", "generator_function_declaration") and name:
            add(prefix + name, "function", n)
        elif t == "method_definition" and name:
            add(prefix + name, "method", n)
        elif t == "variable_declarator" and name:
            v = n.child_by_field_name("value")
            if v is not None and v.type in ("arrow_function", "function_expression", "function"):
                add(prefix + name, "function", n)
        for c in reversed(n.children):
            np = prefix + name + "." if t in ("class_declaration", "class") and name else prefix
            stack.append((c, np, t in ("class_declaration", "class")))
    return sorted(out, key=lambda u: (u.start, u.end))


def _excluded(rel: str, text: str, ws: Workspace, o: DupOptions) -> str | None:
    parts = {p.lower() for p in rel.split("/")[:-1]}
    configured = {x.strip().lower() for x in ws.settings.refactor_dup_exclude.split(",") if x.strip()}
    if parts & configured:
        return "excluded_directory"
    low = rel.lower()
    if any(low.endswith(s) for s in GENERATED_NAMES):
        return "generated_name"
    head = "\n".join(text.split("\n")[:5]).lower()
    if any(m in head for m in GENERATED_MARKERS):
        return "generated_marker"
    for pat in o.exclude_paths:
        if pat and (rel == pat or rel.startswith(pat.rstrip("/") + "/")):
            return "excluded_path"
    if o.exclude_tests and any(h in "/" + low for h in TEST_HINTS):
        return "test_file"
    if o.path_prefix and not rel.startswith(o.path_prefix):
        return "outside_path_filter"
    return None


def _shingles(norm: list[str]) -> set[int]:
    if len(norm) < SHINGLE:
        return {hash(tuple(norm))}
    return {hash(tuple(norm[i:i + SHINGLE])) for i in range(len(norm) - SHINGLE + 1)}


def _h(tokens: list[str]) -> str:
    return hashlib.sha256("\x00".join(tokens).encode()).hexdigest()


def _overlaps(a: Unit, b: Unit) -> bool:
    return a.rel == b.rel and a.start <= b.end and b.start <= a.end


class _UF:
    def __init__(self, n: int) -> None:
        self.p = list(range(n))

    def find(self, x: int) -> int:
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x

    def union(self, a: int, b: int) -> None:
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.p[max(ra, rb)] = min(ra, rb)


def _calls(raw: list[str]) -> set[str]:
    return {raw[i] for i in range(len(raw) - 1) if raw[i + 1] == "(" and (raw[i][:1].isalpha() or raw[i][:1] in "_$") and (i == 0 or raw[i - 1] not in ("def", "class", "function"))} - set(keyword.kwlist)


def _idents(u: Unit) -> set[str]:
    return {r for r, n in zip(u.raw, u.norm, strict=False) if n == "ID"}


def _literals(u: Unit) -> set[str]:
    return {r for r, n in zip(u.raw, u.norm, strict=False) if n in ("NUM", "STR")}


def _ops(u: Unit) -> set[str]:
    return {r for r, n in zip(u.raw, u.norm, strict=False) if r == n and not r[:1].isalnum() and r not in OPERATORS_NOISE}


def _member(u: Unit) -> dict[str, Any]:
    return {"rel_path": u.rel, "name": u.name, "kind": u.kind, "start_line": u.start, "end_line": u.end, "lines": u.end - u.start + 1,
            "tokens": u.tokens, "language": u.language, "excerpt": scrub("\n".join(u.lines[:8]), 600)}


def _strategies(kind: str, differences: dict[str, Any]) -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    if kind == "exact":
        out.append({"id": "extract_shared_function", "summary": "Keep one copy in a shared module and import it from the other locations.",
                    "caution": "Check that the locations genuinely represent the same concept and that no caller depends on the copies diverging later."})
    elif kind == "renamed":
        out.append({"id": "parameterize", "summary": "Merge into one function that takes the differing names or literals as parameters.",
                    "caution": "Only identifiers/literals differ lexically; confirm they play the same role in each copy."})
    else:
        out.append({"id": "reconcile_then_merge", "summary": "First reconcile the listed differences (are they intentional?), then extract the shared part and keep the variation as parameters or a callback.",
                    "caution": "Structural similarity does not imply the differences are harmless."})
    out.append({"id": "leave_as_is", "summary": "Keep the copies when they belong to different modules that change for different reasons.",
                "caution": "Duplication is cheaper than the wrong abstraction when the copies are expected to diverge."})
    if differences.get("behavioral"):
        out[0]["caution"] += " Behavioral differences were detected; see 'differences'."
    return out


def _group_dict(members: list[Unit], kind: str, sim_min: float, sim_avg: float, pairs: list[dict[str, Any]]) -> dict[str, Any]:
    anchor = members[0]
    a_ids, a_lit, a_calls, a_ops = _idents(anchor), _literals(anchor), _calls(anchor.raw), _ops(anchor)
    per: list[dict[str, Any]] = []
    shared_ids = set(a_ids)
    shared_calls = set(a_calls)
    for m in members[1:]:
        ids, lit, calls, ops = _idents(m), _literals(m), _calls(m.raw), _ops(m)
        shared_ids &= ids
        shared_calls &= calls
        per.append({"member": f"{m.rel}:{m.start}", "identifiers_only_in_anchor": sorted(a_ids - ids)[:8], "identifiers_only_in_member": sorted(ids - a_ids)[:8],
                    "literals_only_in_anchor": [scrub(x, 40) for x in sorted(a_lit - lit)[:6]], "literals_only_in_member": [scrub(x, 40) for x in sorted(lit - a_lit)[:6]],
                    "calls_only_in_anchor": sorted(a_calls - calls)[:8], "calls_only_in_member": sorted(calls - a_calls)[:8],
                    "operators_only_in_either": sorted(a_ops ^ ops)[:8]})
    behavioral = any(p["calls_only_in_anchor"] or p["calls_only_in_member"] or p["operators_only_in_either"] or p["literals_only_in_anchor"] or p["literals_only_in_member"] for p in per)
    differences = {"anchor": f"{anchor.rel}:{anchor.start}", "per_member": per[:10], "behavioral": behavioral,
                   "summary": ("No lexical differences." if kind == "exact" else
                               "Only identifier spelling and/or literal values differ." if kind in ("renamed",) and not behavioral else
                               "Differing calls, operators or literals may change behavior; review before merging.")}
    key = "|".join(sorted(f"{m.rel}:{m.start}:{m.end}" for m in members))
    gid = hashlib.sha256(key.encode()).hexdigest()[:12]
    return {"id": gid, "kind": kind, "similarity": round(sim_min, 4), "average_similarity": round(sim_avg, 4),
            "similarity_meaning": ("1.0 = identical token streams." if kind == "exact" else "1.0 = identical after normalising identifiers, numbers and strings." if kind == "renamed"
                                   else "Jaccard overlap of 4-token shingles of the normalised token stream (lowest pair in the group). It indicates textual/structural similarity, not equivalent behavior."),
            "pairs": pairs[:20], "members": [_member(m) for m in members], "lines_total": sum(m.end - m.start + 1 for m in members),
            "shared": {"token_count_range": [min(m.tokens for m in members), max(m.tokens for m in members)], "shared_identifiers": sorted(shared_ids)[:12],
                       "shared_calls": sorted(shared_calls)[:12], "unit_kinds": sorted({m.kind for m in members})},
            "differences": differences, "strategies": _strategies(kind, differences), "auto_merge": False,
            "limitations": ["Detection is lexical/structural; runtime behavior, side effects and callers were not analysed.",
                            "Merging requires an explicit, reviewed refactoring; this analysis never edits files."]}


def analyze(ws: Workspace, o: DupOptions) -> dict[str, Any]:
    max_units = ws.settings.refactor_dup_max_units
    units: list[Unit] = []
    skipped: dict[str, int] = defaultdict(int)
    scanned = 0
    truncated = False
    for rel in ws.paths(o.languages):
        lang = ws.indexed[rel][0]
        got = ws.read(rel)
        if got is None:
            skipped["unreadable"] += 1
            continue
        why = _excluded(rel, got[0], ws, o)
        if why:
            skipped[why] += 1
            continue
        scanned += 1
        us = _py_units(rel, got[0], o) if lang in PY else _js_units(rel, got[0], lang, o)
        units.extend(us)
        if len(units) >= max_units:
            units = units[:max_units]
            truncated = True
            break
    units.sort(key=lambda u: (u.rel, u.start, u.end))
    n = len(units)
    uf = _UF(n)
    edge_sim: dict[tuple[int, int], tuple[float, str]] = {}

    def link(i: int, j: int, sim: float, kind: str) -> None:
        a, b = units[i], units[j]
        if _overlaps(a, b) or (a.kind == "statements") != (b.kind == "statements"):
            return
        edge_sim[(i, j)] = (sim, kind)

    by_raw: dict[str, list[int]] = defaultdict(list)
    by_norm: dict[str, list[int]] = defaultdict(list)
    for i, u in enumerate(units):
        by_raw[_h(u.raw)].append(i)
        by_norm[_h(u.norm)].append(i)
    for idxs in by_raw.values():
        for x in range(len(idxs)):
            for y in range(x + 1, len(idxs)):
                link(idxs[x], idxs[y], 1.0, "exact")
    for idxs in by_norm.values():
        for x in range(len(idxs)):
            for y in range(x + 1, len(idxs)):
                if (idxs[x], idxs[y]) not in edge_sim:
                    link(idxs[x], idxs[y], 1.0, "renamed")
    if "structural" in o.kinds:
        sets = [_shingles(u.norm) if u.kind != "statements" else set() for u in units]
        inv: dict[int, list[int]] = defaultdict(list)
        for i, s in enumerate(sets):
            for sh in s:
                inv[sh].append(i)
        for i, s in enumerate(sets):
            if not s:
                continue
            counts: dict[int, int] = defaultdict(int)
            for sh in s:
                lst = inv[sh]
                if len(lst) > COMMON_SHINGLE_CAP:
                    continue
                for j in lst:
                    if j > i:
                        counts[j] += 1
            for j in counts:
                if (i, j) in edge_sim or not sets[j]:
                    continue
                la, lb = len(units[i].norm), len(units[j].norm)
                if min(la, lb) / max(la, lb) < o.threshold * 0.6:
                    continue
                inter = len(s & sets[j])
                sim = inter / (len(s) + len(sets[j]) - inter)
                if sim >= o.threshold:
                    link(i, j, sim, "structural")
    for (i, j), (_, kind) in edge_sim.items():
        if kind in o.kinds:
            uf.union(i, j)
    comps: dict[int, list[int]] = defaultdict(list)
    for (i, j), (_, kind) in edge_sim.items():
        if kind in o.kinds:
            comps[uf.find(i)].extend([i, j])
    groups: list[dict[str, Any]] = []
    for idxs in comps.values():
        mem = sorted(set(idxs), key=lambda k: (units[k].rel, units[k].start))
        edges = [(s, k) for (i, j), (s, k) in edge_sim.items() if i in mem and j in mem and k in o.kinds]
        kind = max((k for _, k in edges), key=lambda k: KIND_RANK[k])
        sims = [s for s, _ in edges]
        pair_list = sorted(({"a": f"{units[i].rel}:{units[i].start}", "b": f"{units[j].rel}:{units[j].start}", "kind": k, "similarity": round(sm, 4)}
                            for (i, j), (sm, k) in edge_sim.items() if i in mem and j in mem and k in o.kinds), key=lambda p: (KIND_RANK[p["kind"]], -p["similarity"], p["a"], p["b"]))
        groups.append(_group_dict([units[k] for k in mem], kind, min(sims), sum(sims) / len(sims), pair_list))
    ranges = [(m["rel_path"], m["start_line"], m["end_line"]) for g in groups for m in g["members"] if m["kind"] != "statements"]
    groups = [g for g in groups if not (all(m["kind"] == "statements" for m in g["members"]) and all(
        any(r == m["rel_path"] and a <= m["start_line"] and m["end_line"] <= b for r, a, b in ranges) for m in g["members"]))]
    groups.sort(key=lambda g: (KIND_RANK[g["kind"]], -g["similarity"], -g["lines_total"], g["id"]))
    total = len(groups)
    groups = groups[: o.max_groups]
    return {"groups": groups, "total_groups": total, "truncated_groups": total > len(groups),
            "stats": {"files_scanned": scanned, "units_compared": n, "units_truncated": truncated, "skipped": dict(skipped),
                      "duplicated_lines": sum(g["lines_total"] for g in groups)},
            "filters": {"languages": sorted(o.languages), "min_lines": o.min_lines, "min_tokens": o.min_tokens, "threshold": o.threshold,
                        "path_prefix": o.path_prefix, "exclude_paths": o.exclude_paths, "exclude_tests": o.exclude_tests, "kinds": sorted(o.kinds),
                        "include_statement_sequences": o.include_statement_sequences},
            "limitations": ["Functions, methods and (Python) 3-statement windows are compared; copy-pasted fragments smaller than a function may be missed.",
                            f"Shingles occurring in more than {COMMON_SHINGLE_CAP} units are ignored when proposing candidates, so very common idioms are not reported.",
                            "Similarity is not a proof of equivalent behavior and no group is merged automatically."]}
